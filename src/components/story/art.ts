/**
 * Pencil-sketch illustrations of Erika at four ages, drawn on a 400 × 520
 * page with her feet on the same baseline so she visibly grows from page to
 * page. Every stage shares the same face: wide-set dark eyes with a
 * highlight, soft brows, a small curved nose, a gentle smile and rosy
 * cheeks. From her teens a little flower clip sits in her hair.
 *
 * Lines are drawn in order (outline → features → details), so the sketch
 * appears the way an artist would draw it.
 */

export type Stroke = { d: string; w?: number; o?: number };
export type Wash = { d: string; fill: string; o?: number };
export type Dot = { cx: number; cy: number; r: number; fill: string };

export type Art = {
  washes: Wash[];
  /** Cross-hatched shading. */
  hatches: string[];
  lines: (string | Stroke)[];
  dots: Dot[];
  /** Storybook doodles around her, drawn more lightly. */
  decor: (string | Stroke)[];
  decorWashes: Wash[];
  /** Optional transform for the whole figure (e.g. a slight head tilt). */
  transform?: string;
};

const r1 = (n: number) => Math.round(n * 10) / 10;

// ── doodle helpers ───────────────────────────────────────────────────────────

export function ellipse(cx: number, cy: number, rx: number, ry: number) {
  return `M${r1(cx - rx)} ${r1(cy)} a${rx} ${ry} 0 1 0 ${r1(rx * 2)} 0 a${rx} ${ry} 0 1 0 ${r1(-rx * 2)} 0`;
}

export function sparkle(x: number, y: number, s: number) {
  return `M${x} ${y - s} Q${x} ${y} ${x + s} ${y} Q${x} ${y} ${x} ${y + s} Q${x} ${y} ${x - s} ${y} Q${x} ${y} ${x} ${y - s}`;
}

/** A hand-drawn flower: looping petals around a small centre. */
export function flower(x: number, y: number, r: number, petals = 5, turn = 0) {
  let d = "";
  for (let k = 0; k < petals; k++) {
    const a = turn + (k / petals) * Math.PI * 2;
    const p = (ang: number, rad: number) => `${r1(x + Math.cos(ang) * rad)} ${r1(y + Math.sin(ang) * rad)}`;
    d += `M${r1(x)} ${r1(y)} Q${p(a - 0.55, r * 1.25)} ${p(a, r)} Q${p(a + 0.55, r * 1.25)} ${r1(x)} ${r1(y)} `;
  }
  return d + ellipse(x, y, r * 0.22, r * 0.22);
}

export function butterfly(x: number, y: number, s: number) {
  return (
    `M${x} ${y} C${x - s * 1.2} ${y - s * 1.3} ${x - s * 1.6} ${y - s * 0.2} ${x - s * 0.2} ${y + s * 0.1} ` +
    `C${x - s * 1.1} ${y + s * 0.5} ${x - s * 0.8} ${y + s * 1.2} ${x} ${y + s * 0.3} ` +
    `M${x} ${y} C${x + s * 1.2} ${y - s * 1.3} ${x + s * 1.6} ${y - s * 0.2} ${x + s * 0.2} ${y + s * 0.1} ` +
    `C${x + s * 1.1} ${y + s * 0.5} ${x + s * 0.8} ${y + s * 1.2} ${x} ${y + s * 0.3} ` +
    `M${x - s * 0.1} ${y - s * 0.2} Q${x - s * 0.4} ${y - s * 0.9} ${x - s * 0.7} ${y - s * 1.1} ` +
    `M${x + s * 0.1} ${y - s * 0.2} Q${x + s * 0.4} ${y - s * 0.9} ${x + s * 0.7} ${y - s * 1.1}`
  );
}

export function note(x: number, y: number, s = 1) {
  return `M${x} ${y} L${x} ${r1(y - 22 * s)} Q${r1(x + 8 * s)} ${r1(y - 18 * s)} ${r1(x + 10 * s)} ${r1(y - 10 * s)} ${ellipse(x - 4 * s, y, 4.5 * s, 3.2 * s)}`;
}

/** A curling stem with a few leaves. */
export function sprig(x: number, y: number, h: number, lean: number) {
  const tx = x + lean;
  const ty = y - h;
  let d = `M${x} ${y} Q${r1(x + lean * 0.2)} ${r1(y - h * 0.6)} ${r1(tx)} ${r1(ty)} `;
  for (let k = 1; k <= 3; k++) {
    const t = k / 4;
    const px = r1(x + lean * t * t);
    const py = r1(y - h * t);
    const side = k % 2 ? 1 : -1;
    d += `M${px} ${py} Q${r1(px + side * 12)} ${r1(py - 10)} ${r1(px + side * 16)} ${r1(py - 2)} Q${r1(px + side * 8)} ${r1(py + 2)} ${px} ${py} `;
  }
  return d;
}

