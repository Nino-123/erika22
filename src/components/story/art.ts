/**
 * Her face, scaled by age. (cx, cy) is the centre of the eyes' line;
 * `s` scales spacing; `eye` is the iris radius.
 */
function face(cx: number, cy: number, s: number, eye: number, opts: { lashes?: boolean; lowerLip?: boolean } = {}) {
  const ex = 16 * s;
  const lid = (x: number) => `M${r1(x - 9.5 * s)} ${r1(cy - 1)} C${r1(x - 6 * s)} ${r1(cy - 8.5 * s)} ${r1(x + 6 * s)} ${r1(cy - 8.5 * s)} ${r1(x + 9.5 * s)} ${r1(cy - 1)}`;
  const brow = (x: number, dir: number) =>
    `M${r1(x - 8 * s * dir)} ${r1(cy - 13 * s)} C${r1(x - 3 * s * dir)} ${r1(cy - 17 * s)} ${r1(x + 3 * s * dir)} ${r1(cy - 17 * s)} ${r1(x + 7 * s * dir)} ${r1(cy - 14 * s)}`;
  const lines: Stroke[] = [
    { d: brow(cx - ex, 1), w: 1.2, o: 0.7 },
    { d: brow(cx + ex, -1), w: 1.2, o: 0.7 },
    { d: lid(cx - ex), w: 1.6 },
    { d: lid(cx + ex), w: 1.6 },
    { d: `M${r1(cx - 1.5 * s)} ${r1(cy + 11 * s)} C${r1(cx)} ${r1(cy + 15 * s)} ${r1(cx + 3 * s)} ${r1(cy + 15.5 * s)} ${r1(cx + 3.5 * s)} ${r1(cy + 13 * s)}`, w: 1.1, o: 0.75 },
    { d: `M${r1(cx - 8 * s)} ${r1(cy + 22 * s)} C${r1(cx - 3 * s)} ${r1(cy + 27.5 * s)} ${r1(cx + 3 * s)} ${r1(cy + 27.5 * s)} ${r1(cx + 8 * s)} ${r1(cy + 22 * s)}`, w: 1.4 },
  ];
  if (opts.lashes) {
    lines.push(
      { d: `M${r1(cx - ex - 9.5 * s)} ${r1(cy - 1)} l${r1(-3.5 * s)} ${r1(-3 * s)}`, w: 1.1 },
      { d: `M${r1(cx + ex + 9.5 * s)} ${r1(cy - 1)} l${r1(3.5 * s)} ${r1(-3 * s)}`, w: 1.1 },
    );
  }
  if (opts.lowerLip) {
    lines.push({ d: `M${r1(cx - 4 * s)} ${r1(cy + 27 * s)} C${r1(cx - 1 * s)} ${r1(cy + 29 * s)} ${r1(cx + 1 * s)} ${r1(cy + 29 * s)} ${r1(cx + 4 * s)} ${r1(cy + 27 * s)}`, w: 0.9, o: 0.55 });
  }
  const dots: Dot[] = [
    { cx: r1(cx - ex), cy: r1(cy + 0.5), r: eye, fill: INK.iris },
    { cx: r1(cx + ex), cy: r1(cy + 0.5), r: eye, fill: INK.iris },
    { cx: r1(cx - ex + eye * 0.35), cy: r1(cy - eye * 0.35), r: r1(eye * 0.32), fill: "#fffaf6" },
    { cx: r1(cx + ex + eye * 0.35), cy: r1(cy - eye * 0.35), r: r1(eye * 0.32), fill: "#fffaf6" },
  ];
  const blush: Wash[] = [
    { d: ellipse(cx - ex - 6 * s, cy + 17 * s, 8 * s, 4.5 * s), fill: INK.blush, o: 0.55 },
    { d: ellipse(cx + ex + 6 * s, cy + 17 * s, 8 * s, 4.5 * s), fill: INK.blush, o: 0.55 },
  ];
  return { lines, dots, blush };
}

